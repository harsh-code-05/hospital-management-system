BEGIN;
SET LOCAL search_path TO public, pg_catalog;
SET LOCAL lock_timeout = '5s';

-- 1. Document Catalog: stores metadata for encrypted doctor verification evidence.
CREATE TABLE public.doctor_verification_documents (
    id uuid PRIMARY KEY,
    doctor_id bigint NOT NULL REFERENCES public.doctors (id),
    document_kind varchar(32) NOT NULL CHECK (document_kind IN ('ID_PROOF', 'QUALIFICATION')),
    storage_key varchar(128) NOT NULL CONSTRAINT uk_doctor_verification_documents_storage_key UNIQUE,
    media_type varchar(64) NOT NULL CHECK (media_type IN ('image/jpeg', 'image/png')),
    file_size bigint NOT NULL CHECK (file_size > 0 AND file_size <= 5242880),
    checksum varchar(64) NOT NULL CHECK (char_length(checksum) = 64 AND checksum ~ '^[0-9a-f]{64}$'),
    created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    retired_at timestamp with time zone,
    purge_deadline timestamp with time zone,
    purged_at timestamp with time zone,
    CONSTRAINT ck_doc_retired_after_created CHECK (retired_at IS NULL OR retired_at >= created_at),
    CONSTRAINT ck_doc_purge_deadline CHECK (purge_deadline IS NULL OR retired_at IS NOT NULL),
    CONSTRAINT ck_doc_purged_after_retired CHECK (purged_at IS NULL OR (retired_at IS NOT NULL AND purged_at >= retired_at))
);

-- Exactly one active version per doctor and document kind.
CREATE UNIQUE INDEX uk_doctor_verification_documents_active
    ON public.doctor_verification_documents (doctor_id, document_kind)
    WHERE (retired_at IS NULL);

-- Fast lookup for doctor verification history by kind.
CREATE INDEX ix_doctor_verification_documents_doctor_kind
    ON public.doctor_verification_documents (doctor_id, document_kind, created_at DESC);

-- Fast lookup for eligible retention purge candidates.
CREATE INDEX ix_doctor_verification_documents_purge_scan
    ON public.doctor_verification_documents (purge_deadline)
    WHERE retired_at IS NOT NULL AND purged_at IS NULL;

-- 2. Document Audit Events: append-only compliance log for evidence lifecycle.
CREATE TABLE public.doctor_verification_document_events (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_type varchar(32) NOT NULL CHECK (
        event_type IN ('DOCUMENT_ATTACHED', 'DOCUMENT_REPLACED', 'DOCUMENT_DETACHED', 'DOCUMENT_PURGED', 'ADMIN_ACCESS_GRANTED')
    ),
    doctor_id bigint NOT NULL REFERENCES public.doctors (id),
    document_id uuid REFERENCES public.doctor_verification_documents (id) ON DELETE SET NULL,
    document_kind varchar(32) NOT NULL CHECK (document_kind IN ('ID_PROOF', 'QUALIFICATION')),
    actor_user_id bigint REFERENCES public.users (id),
    actor_role varchar(16) NOT NULL CHECK (actor_role IN ('DOCTOR', 'ADMIN', 'SYSTEM')),
    outcome varchar(16) NOT NULL CHECK (outcome IN ('SUCCESS', 'FAILURE')),
    correlation_id varchar(64) NOT NULL CHECK (btrim(correlation_id) <> ''),
    details varchar(500),
    occurred_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_doctor_verification_document_events_actor CHECK (
        (actor_role = 'SYSTEM' AND actor_user_id IS NULL)
        OR (actor_role IN ('DOCTOR', 'ADMIN') AND actor_user_id IS NOT NULL)
    )
);

CREATE INDEX ix_doctor_verification_document_events_doctor
    ON public.doctor_verification_document_events (doctor_id, occurred_at DESC, id DESC);

CREATE INDEX ix_doctor_verification_document_events_doc
    ON public.doctor_verification_document_events (document_id, occurred_at DESC)
    WHERE document_id IS NOT NULL;

CREATE INDEX ix_doctor_verification_document_events_correlation
    ON public.doctor_verification_document_events (correlation_id);

COMMIT;
