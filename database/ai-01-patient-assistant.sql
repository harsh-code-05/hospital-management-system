BEGIN;
SET LOCAL search_path TO public, pg_catalog;
SET LOCAL lock_timeout = '5s';

CREATE TABLE public.ai_chat_sessions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id bigint NOT NULL REFERENCES public.patients (id),
    title varchar(80) NOT NULL CHECK (btrim(title) <> ''),
    created_at timestamp(6) without time zone NOT NULL DEFAULT LOCALTIMESTAMP,
    updated_at timestamp(6) without time zone NOT NULL DEFAULT LOCALTIMESTAMP
);

CREATE INDEX ix_ai_chat_sessions_patient_updated
    ON public.ai_chat_sessions (patient_id, updated_at DESC, id DESC);

CREATE TABLE public.ai_chat_messages (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id bigint NOT NULL REFERENCES public.ai_chat_sessions (id) ON DELETE CASCADE,
    role varchar(16) NOT NULL CHECK (role IN ('USER', 'ASSISTANT')),
    content varchar(8000) NOT NULL CHECK (
        btrim(content) <> '' AND (role <> 'USER' OR char_length(content) <= 2000)
    ),
    request_id uuid NOT NULL,
    include_appointments boolean NOT NULL DEFAULT false,
    created_at timestamp(6) without time zone NOT NULL DEFAULT LOCALTIMESTAMP,
    CONSTRAINT uk_ai_chat_message_request_role UNIQUE (session_id, request_id, role)
);

CREATE INDEX ix_ai_chat_messages_session_id
    ON public.ai_chat_messages (session_id, id DESC);

COMMIT;
