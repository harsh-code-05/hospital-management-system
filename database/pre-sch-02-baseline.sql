BEGIN;

CREATE TABLE public.users (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email varchar(255) NOT NULL UNIQUE,
    password varchar(255),
    role varchar(255) NOT NULL CHECK (role IN ('PATIENT', 'DOCTOR', 'ADMIN')),
    google_id varchar(255) UNIQUE
);

CREATE TABLE public.specializations (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(255) NOT NULL UNIQUE,
    description varchar(255)
);

CREATE TABLE public.patients (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name varchar(255),
    last_name varchar(255),
    date_of_birth date,
    gender varchar(255),
    phone varchar(255),
    user_id bigint NOT NULL UNIQUE REFERENCES public.users (id)
);

CREATE TABLE public.doctors (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name varchar(255),
    last_name varchar(255),
    qualification varchar(255),
    experience integer,
    user_id bigint NOT NULL UNIQUE REFERENCES public.users (id),
    specialization_id bigint NOT NULL REFERENCES public.specializations (id)
);

CREATE TABLE public.doctor_applications (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL UNIQUE REFERENCES public.users (id),
    specialization_id bigint NOT NULL REFERENCES public.specializations (id),
    first_name varchar(255) NOT NULL,
    last_name varchar(255) NOT NULL,
    qualification varchar(255) NOT NULL,
    experience integer NOT NULL,
    status varchar(255) NOT NULL CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED')),
    rejection_reason varchar(255),
    created_at timestamp(6) without time zone,
    reviewed_at timestamp(6) without time zone,
    reviewed_by_user_id bigint REFERENCES public.users (id)
);

CREATE TABLE public.doctor_availability (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date date,
    start_time time(0) without time zone,
    end_time time(0) without time zone,
    doctor_id bigint NOT NULL REFERENCES public.doctors (id)
);

CREATE TABLE public.appointment_slots (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date date,
    start_time time(0) without time zone,
    end_time time(0) without time zone,
    status varchar(255) CHECK (status IN ('AVAILABLE', 'BOOKED', 'BLOCKED')),
    doctor_id bigint NOT NULL REFERENCES public.doctors (id),
    CONSTRAINT uk_doctor_slot_time UNIQUE (doctor_id, date, start_time, end_time)
);

CREATE TABLE public.appointments (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reason varchar(255),
    created_at timestamp(6) without time zone,
    status varchar(255) CHECK (status IN ('CONFIRMED', 'COMPLETED', 'CANCELLED', 'NO_SHOW')),
    patient_id bigint NOT NULL REFERENCES public.patients (id),
    doctor_id bigint NOT NULL REFERENCES public.doctors (id),
    slot_id bigint NOT NULL REFERENCES public.appointment_slots (id)
);

CREATE TABLE public.audit_logs (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_type varchar(255) NOT NULL CHECK (event_type IN (
        'LOGIN_SUCCESS', 'LOGIN_FAILURE',
        'PATIENT_BOOKED_APPOINTMENT', 'PATIENT_CANCELLED_APPOINTMENT',
        'DOCTOR_CANCELLED_APPOINTMENT', 'ADMIN_CANCELLED_APPOINTMENT',
        'DOCTOR_COMPLETED_APPOINTMENT', 'ADMIN_COMPLETED_APPOINTMENT',
        'DOCTOR_CREATED_AVAILABILITY', 'DOCTOR_UPDATED_AVAILABILITY',
        'ADMIN_CREATED_DOCTOR', 'ADMIN_UPDATED_DOCTOR'
    )),
    performed_by_email varchar(255) NOT NULL,
    performed_by_role varchar(255),
    entity_name varchar(255),
    entity_id bigint,
    details varchar(1000),
    ip_address varchar(255),
    "timestamp" timestamp(6) without time zone NOT NULL
);

COMMIT;
